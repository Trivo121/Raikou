def test_search_rejects_products_outside_the_pipeline_contract(monkeypatch):
    """Defence in depth: a provider-side change must not reach the pipeline."""
    _install(monkeypatch, lambda request: httpx.Response(200, json=_fixture("cdse_search.json")))

    results = copernicus.search_products(bbox=BBOX, start=START, end=END, limit=20)

    names = [product.name for product in results]
    assert len(results) == 2
    assert all("_IW_GRDH_1SDV_" in name for name in names)
    # The GRDM and the single-pol 1SSV entries in the fixture are dropped.
    assert not any("GRDM" in name for name in names)
    assert not any("1SSV" in name for name in names)


