def test_token_request_uses_the_client_credentials_grant(monkeypatch):
    seen = _install(monkeypatch, lambda request: _token_response())

    copernicus.access_token()

    body = parse_qs(seen[0].content.decode("utf-8"))
    assert body["grant_type"] == ["client_credentials"]
    assert body["client_id"] == ["test-client"]
    # The password grant must never appear: no account password is handled here.
    assert "username" not in body
    assert "password" not in body


def test_token_expiry_honours_the_refresh_margin(monkeypatch):
    """A token valid for exactly the margin is already treated as expired."""
    monkeypatch.setattr(settings, "COPERNICUS_TOKEN_REFRESH_MARGIN_SECONDS", 60)
    seen = _install(
        monkeypatch,
        lambda request: httpx.Response(200, json={"access_token": "short", "expires_in": 60}),
    )

    clock = {"now": 1000.0}
    monkeypatch.setattr(copernicus.time, "monotonic", lambda: clock["now"])

    assert copernicus.access_token() == "short"
    clock["now"] += 2.0
    copernicus.access_token()

    # 60s lifetime minus a 60s margin clamps to a 1s window, so the second
    # call two seconds later must re-mint rather than serve a stale token.
    assert len(seen) == 2


