def _dropping_content(chunks: list[bytes], drop_after: int):
    def generator():
        for index, chunk in enumerate(chunks):
            if index == drop_after:
                raise httpx.ReadError("connection reset by peer")
            yield chunk

    return generator()


@pytest.fixture
def small_chunks(monkeypatch):
    """Shrink the read chunk so a drop leaves bytes actually on disk.

    ``iter_bytes`` re-chunks and buffers: at the production 1 MiB size a drop
    inside the first megabyte yields nothing at all, so ``written`` stays 0 and
    the retry is a plain restart rather than a resume. That is correct
    behaviour -- we only ever resume from bytes we really wrote -- but it means
    the resume path needs a smaller chunk to be observable in a test.
    """
    monkeypatch.setattr(copernicus, "_DOWNLOAD_CHUNK_BYTES", 10)


def test_download_resumes_with_a_range_header_after_a_drop(monkeypatch, small_chunks, tmp_path):
    full = b"0123456789" * 10
    attempts = {"count": 0}

    def handler(request: httpx.Request) -> httpx.Response:
        if request.url.path.endswith("/token"):
            return _token_response()
        attempts["count"] += 1
        if attempts["count"] == 1:
            return httpx.Response(200, content=_dropping_content([full[:40], full[40:]], 1))
        start = int(request.headers["range"].removeprefix("bytes=").rstrip("-"))
        return httpx.Response(206, content=full[start:])

    seen = _install(monkeypatch, handler)
    destination = tmp_path / "product.zip"

    written = copernicus.download_product_to(
        PRODUCT_ID, str(destination), expected_size_bytes=len(full)
    )

    assert written == len(full)
    assert destination.read_bytes() == full
    ranged = [request for request in seen if "range" in {k.lower() for k in request.headers}]
    assert ranged and ranged[0].headers["range"] == "bytes=40-"


def test_download_restarts_when_the_server_ignores_the_range(monkeypatch, small_chunks, tmp_path):
    """A 200 answer to a Range request means the whole body is coming again.

    Appending it to the partial file would silently corrupt the archive.
    """
    full = b"ABCDEFGHIJ" * 10
    attempts = {"count": 0}

    def handler(request: httpx.Request) -> httpx.Response:
        if request.url.path.endswith("/token"):
            return _token_response()
        attempts["count"] += 1
        if attempts["count"] == 1:
            return httpx.Response(200, content=_dropping_content([full[:30], full[30:]], 1))
        return httpx.Response(200, content=full)

    seen = _install(monkeypatch, handler)
    destination = tmp_path / "product.zip"

    written = copernicus.download_product_to(
        PRODUCT_ID, str(destination), expected_size_bytes=len(full)
    )

    # The second request did ask to resume, and the server ignored it.
    ranged = [request for request in seen if "range" in {k.lower() for k in request.headers}]
    assert ranged and ranged[0].headers["range"] == "bytes=30-"
    assert written == len(full)
    assert destination.read_bytes() == full


