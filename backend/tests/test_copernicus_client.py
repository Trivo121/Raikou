def test_download_refreshes_the_token_once_on_401(monkeypatch, tmp_path):
    tokens = {"issued": 0}
    payload = b"recovered"

    def handler(request: httpx.Request) -> httpx.Response:
        if request.url.path.endswith("/token"):
            tokens["issued"] += 1
            return httpx.Response(
                200, json={"access_token": f"token-{tokens['issued']}", "expires_in": 600}
            )
        if request.headers.get("authorization") == "Bearer token-1":
            return httpx.Response(401, text="expired")
        return httpx.Response(200, content=payload)

    _install(monkeypatch, handler)
    destination = tmp_path / "product.zip"

    written = copernicus.download_product_to(PRODUCT_ID, str(destination))

    assert written == len(payload)
    assert tokens["issued"] == 2


