"""Offline tests for the CDSE client. No network, no quota.

Every request is served by an ``httpx.MockTransport``, injected through the
``_http_client`` seam. The fixtures under ``tests/fixtures`` were captured by
hand once and trimmed; they are not regenerated by the suite.
"""

